#!/usr/bin/env python3
"""Bake a small, real departures extract for the welcome page's board.

The welcome page is shown before any pack is installed, so it cannot read the
13.8 MB stops pack. The board there is the product's own object, and it has to
hold real departures rather than invented ones, so a handful of true rows are
written into the source at release time and the release id is recorded with
them. Regenerate whenever the release changes.
"""
from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path

RELEASE = Path("artifacts/releases/odivrelo")
OUT = Path("apps/web/src/data/boardSample.generated.json")
ROWS = 7


def main() -> int:
    manifest = json.loads((RELEASE / "manifest.json").read_text(encoding="utf-8"))
    dates = sorted(k for k in manifest["files"] if k.startswith("journeys-"))
    if not dates:
        print("no journey packs in the release", file=sys.stderr)
        return 1
    # The soonest service date that has not already gone, not simply the first
    # pack in the release: taking the earliest put a board of departures from
    # three weeks ago on the welcome page, every row of it correctly but
    # uselessly marked out of date.
    today = date.today().isoformat()
    upcoming = [k for k in dates if k[len("journeys-"):len("journeys-") + 10] >= today]
    chosen = upcoming[0] if upcoming else dates[-1]
    pack = json.loads((RELEASE / manifest["files"][chosen]["path"]).read_text(encoding="utf-8"))
    results = pack.get("results", [])
    if not results:
        print("the first journey pack has no results", file=sys.stderr)
        return 1

    # One origin, so the board reads as one terminal's board rather than a
    # shuffle of unrelated places, and the busiest one on the day, so the board
    # is full: taking whichever origin happened to come first produced a board
    # with a single row on it.
    by_origin: dict[str, list[dict]] = {}
    for r in results:
        by_origin.setdefault(r["departure"]["stopId"], []).append(r)
    busiest = max(by_origin.values(), key=len)
    origin = busiest[0]["departure"]
    same = sorted(busiest, key=lambda r: r["departure"]["at"])

    rows = []
    for r in same[:ROWS]:
        freshness = r.get("freshness") or {}
        rows.append({
            "at": r["departure"]["at"],
            "destination": r["arrival"]["stopName"],
            "operator": (r.get("operator") or {}).get("name"),
            "quality": r["departure"].get("quality"),
            # The last column of the board, and the whole idea of the product:
            # when this row was last checked, and how old that makes it.
            "checkedAt": freshness.get("checkedAt"),
            "freshness": freshness.get("state"),
        })

    out = {
        "$comment": "Generated by scripts/generate-board-sample.py from the published release. Real departures; do not hand-edit.",
        "releaseId": manifest["releaseId"],
        "serviceDate": pack.get("serviceDate"),
        "originName": origin["stopName"],
        "rows": rows,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(rows)} real departures from {origin['stopName'].get('el')})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
